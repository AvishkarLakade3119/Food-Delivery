# ???????????????????????????????????????????????????????????
# Food Delivery Platform - Complete Recovery Script
# Run this after: minikube start, jenkins rebuild, PC reboot
# ???????????????????????????????????????????????????????????

param(
    [switch]$SkipTunnel  # Skip Cloudflare tunnel restart
)

Write-Host "`n????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?   ?? FOOD DELIVERY PLATFORM - AUTO RECOVERY ??           ?" -ForegroundColor Cyan
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Cyan

# ???????????????????????????????????????????????????????????
# STEP 1: Verify Minikube is running
# ???????????????????????????????????????????????????????????
Write-Host "`n[1/8] Checking Minikube..." -ForegroundColor Yellow
$mkStatus = minikube status 2>&1 | Out-String
if ($mkStatus -match "Running") {
    Write-Host "  ? Minikube is running" -ForegroundColor Green
} else {
    Write-Host "  ?? Minikube not running, starting..." -ForegroundColor Yellow
    minikube start --driver=docker --memory=6144 --cpus=2
}

# Refresh kubeconfig for Jenkins
Write-Host "`n[2/8] Refreshing kubeconfig..." -ForegroundColor Yellow
$src = "$env:USERPROFILE\.kube\config"
kubectl config view --flatten --raw | Out-File "$src.flat" -Encoding ascii

$jenkinsPath = "C:\ProgramData\Jenkins\.jenkins\.kube"
if (-not (Test-Path $jenkinsPath)) { New-Item -ItemType Directory -Path $jenkinsPath -Force | Out-Null }
Copy-Item "$src.flat" "$jenkinsPath\config" -Force -ErrorAction SilentlyContinue
Write-Host "  ? Jenkins kubeconfig updated" -ForegroundColor Green

# ???????????????????????????????????????????????????????????
# STEP 3: Kill zombie processes
# ???????????????????????????????????????????????????????????
Write-Host "`n[3/8] Cleaning up zombie processes..." -ForegroundColor Yellow
Get-Process kubectl -ErrorAction SilentlyContinue | Where-Object { 
    $_.MainWindowTitle -notmatch "KUBECTL-PROXY" 
} | Stop-Process -Force -ErrorAction SilentlyContinue

Start-Sleep -Seconds 3
Write-Host "  ? Cleanup complete" -ForegroundColor Green

# ???????????????????????????????????????????????????????????
# STEP 4: Start kubectl proxy (with auto-restart!)
# ???????????????????????????????????????????????????????????
Write-Host "`n[4/8] Starting kubectl proxy (auto-restart enabled)..." -ForegroundColor Yellow

# Check if proxy already running
$proxyRunning = $false
try {
    $r = Invoke-WebRequest "http://localhost:8001/api/v1/namespaces" -UseBasicParsing -TimeoutSec 3
    Write-Host "  ? kubectl proxy already running" -ForegroundColor Green
    $proxyRunning = $true
} catch {}

if (-not $proxyRunning) {
    Start-Process powershell -ArgumentList @(
        "-NoExit",
        "-Command",
        "`$Host.UI.RawUI.WindowTitle='KUBECTL-PROXY (AUTO-RESTART)'; Write-Host 'kubectl proxy - Prometheus needs this!' -ForegroundColor Green; while(`$true) { kubectl proxy --address=0.0.0.0 --accept-hosts='.*' --port=8001; Write-Host 'Died - restarting in 3s...' -ForegroundColor Yellow; Start-Sleep -Seconds 3 }"
    )
    
    # Wait for it to be ready
    for ($i = 1; $i -le 10; $i++) {
        try {
            $r = Invoke-WebRequest "http://localhost:8001/api/v1/namespaces" -UseBasicParsing -TimeoutSec 3
            Write-Host "  ? kubectl proxy started" -ForegroundColor Green
            break
        } catch {
            Start-Sleep -Seconds 2
        }
    }
}

# ???????????????????????????????????????????????????????????
# STEP 5: Start monitoring containers
# ???????????????????????????????????????????????????????????
Write-Host "`n[5/8] Starting monitoring containers..." -ForegroundColor Yellow

$containers = @("prometheus", "grafana", "postgres-exporter-user", "postgres-exporter-restaurant", 
                "postgres-exporter-order", "postgres-exporter-payment", "postgres-exporter-notification",
                "rabbitmq-exporter")

foreach ($c in $containers) {
    $running = docker ps --filter "name=^${c}$" --format "{{.Names}}" 2>&1
    if ($running -match $c) {
        Write-Host "  ? $c already running" -ForegroundColor Green
    } else {
        docker start $c 2>&1 | Out-Null
        if ($LASTEXITCODE -eq 0) {
            Write-Host "  ? Started $c" -ForegroundColor Green
        } else {
            Write-Host "  ?? $c not found (may not exist yet)" -ForegroundColor Gray
        }
    }
}

# ???????????????????????????????????????????????????????????
# STEP 6: Wait for pods to be ready
# ???????????????????????????????????????????????????????????
Write-Host "`n[6/8] Waiting for K8s pods..." -ForegroundColor Yellow

$maxWait = 20  # 10 minutes
for ($i = 1; $i -le $maxWait; $i++) {
    $pods = kubectl get pods -n food-delivery --no-headers 2>$null
    $ready = ($pods | Where-Object { $_ -match "1/1\s+Running" }).Count
    $total = ($pods | Measure-Object).Count
    
    if ($ready -ge 11) {
        Write-Host "  ? All 11 pods Ready!" -ForegroundColor Green
        break
    }
    Write-Host "  [$($i * 30)s] Ready: $ready/$total" -ForegroundColor Gray
    Start-Sleep -Seconds 30
}

# ???????????????????????????????????????????????????????????
# STEP 7: Start port-forward for K8s RabbitMQ UI
# ???????????????????????????????????????????????????????????
Write-Host "`n[7/8] Starting RabbitMQ UI port-forward..." -ForegroundColor Yellow

$rmqPfRunning = netstat -ano | findstr ":15673" | findstr "LISTENING"
if ($rmqPfRunning) {
    Write-Host "  ? RabbitMQ UI port-forward already running" -ForegroundColor Green
} else {
    Start-Process powershell -ArgumentList @(
        "-NoExit",
        "-Command",
        "`$Host.UI.RawUI.WindowTitle='pf-rabbitmq-k8s'; Write-Host 'K8s RabbitMQ UI on http://localhost:15673' -ForegroundColor Green; while(`$true) { kubectl port-forward -n food-delivery svc/rabbitmq 15673:15672; Start-Sleep -Seconds 3 }"
    )
    Write-Host "  ? Started RabbitMQ UI port-forward" -ForegroundColor Green
}

# ???????????????????????????????????????????????????????????
# STEP 8: Verify everything
# ???????????????????????????????????????????????????????????
Write-Host "`n[8/8] Verification..." -ForegroundColor Yellow

Start-Sleep -Seconds 10

# Prometheus targets
Write-Host "`n--- Prometheus ---" -ForegroundColor Cyan
try {
    $t = Invoke-RestMethod "http://localhost:9090/api/v1/targets" -TimeoutSec 5
    $up = ($t.data.activeTargets | Where-Object { $_.health -eq "up" }).Count
    $total = $t.data.activeTargets.Count
    Write-Host "  Targets UP: $up / $total" -ForegroundColor $(if($up -eq $total){"Green"}else{"Yellow"})
} catch { Write-Host "  ? Not reachable yet" -ForegroundColor Red }

# K8s pods
Write-Host "`n--- Kubernetes ---" -ForegroundColor Cyan
$pods = kubectl get pods -n food-delivery --no-headers 2>$null
$ready = ($pods | Where-Object { $_ -match "1/1\s+Running" }).Count
Write-Host "  Pods Ready: $ready / 11" -ForegroundColor $(if($ready -ge 11){"Green"}else{"Yellow"})

# RabbitMQ
Write-Host "`n--- RabbitMQ ---" -ForegroundColor Cyan
$rmqPod = kubectl get pods -n food-delivery -l app=rabbitmq -o jsonpath='{.items[0].metadata.name}' 2>$null
if ($rmqPod) {
    $conns = (kubectl exec $rmqPod -n food-delivery -- rabbitmqctl list_connections 2>&1 | Select-String "guest").Count
    Write-Host "  Connections: $conns" -ForegroundColor $(if($conns -ge 3){"Green"}else{"Yellow"})
}

# Zipkin
Write-Host "`n--- Zipkin ---" -ForegroundColor Cyan
try {
    $svcs = Invoke-RestMethod "http://localhost:9411/api/v2/services" -TimeoutSec 5
    Write-Host "  Services traced: $($svcs.Count)" -ForegroundColor Green
} catch { Write-Host "  ?? Not reachable" -ForegroundColor Yellow }

Write-Host "`n????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host "?   ? RECOVERY COMPLETE! ?                                ?" -ForegroundColor Green
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Green

Write-Host "`n?? ACCESS URLS:" -ForegroundColor Cyan
Write-Host "  Prometheus:    http://localhost:9090/targets" -ForegroundColor White
Write-Host "  Grafana:       http://localhost:3000" -ForegroundColor White
Write-Host "  RabbitMQ K8s:  http://localhost:15673" -ForegroundColor White
Write-Host "  Zipkin:        http://localhost:9411" -ForegroundColor White
Write-Host "  Jenkins:       http://localhost:9000" -ForegroundColor White

Write-Host "`n?? IMPORTANT:" -ForegroundColor Yellow
Write-Host "  Keep these windows OPEN:" -ForegroundColor White
Write-Host "    ? KUBECTL-PROXY (Prometheus needs it)" -ForegroundColor White
Write-Host "    ? pf-rabbitmq-k8s (RabbitMQ UI needs it)" -ForegroundColor White